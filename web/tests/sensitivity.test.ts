import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, it } from "vitest";
import { DEFAULT_FUZZY_PARAMS, type FuzzyParams } from "@/lib/rules";
import type { Action } from "@/lib/types";
import { SCENARIOS, runScenario } from "./scenarioRunner";

const STEP = 0.1;
const DOMAIN_EDGES = new Set([0, 1, 8, 100]);

type Perturb = (p: FuzzyParams, f: number) => FuzzyParams;

function scaleInner<T extends number[]>(values: T, f: number): T {
  return values.map((v) => (DOMAIN_EDGES.has(v) ? v : Math.min(100, v * f))) as T;
}

function output(key: keyof FuzzyParams["output"]): Perturb {
  return (p, f) => ({ ...p, output: { ...p.output, [key]: scaleInner([...p.output[key]], f) } });
}

function cut(i: 0 | 1 | 2): Perturb {
  return (p, f) => {
    const cuts: FuzzyParams["cuts"] = [...p.cuts];
    cuts[i] = p.cuts[i] * f;
    return { ...p, cuts };
  };
}

const PARAMETERS: [string, Perturb][] = [
  ["output keep trap(0,0,20,40)", output("keep")],
  ["output monitor tri(25,45,60)", output("monitor")],
  ["output soon tri(50,70,85)", output("soon")],
  ["output now trap(75,90,100,100)", output("now")],
  ["R4 weight 0.5 (breaded)", (p, f) => ({ ...p, weights: { ...p.weights, R4: p.weights.R4 * f } })],
  ["R5 weight 0.5 (Cox)", (p, f) => ({ ...p, weights: { ...p.weights, R5: p.weights.R5 * f } })],
  ["cut-off keep/monitor 30", cut(0)],
  ["cut-off monitor/change_soon 55", cut(1)],
  ["cut-off change_soon/change_now 75", cut(2)],
  ["breaded breakpoints (0.25, 0.5)", (p, f) => ({ ...p, breaded: scaleInner([...p.breaded], f) })],
  ["Cox breakpoints (2, 4)", (p, f) => ({ ...p, cox: scaleInner([...p.cox], f) })],
];

function evaluate(params: FuzzyParams, baseline: Action[]) {
  const actions = SCENARIOS.map((s) => runScenario(s, params).action);
  const changed = actions.filter((a, i) => a !== baseline[i]).length;
  const agreed = actions.filter((a, i) => SCENARIOS[i].expected.includes(a)).length;
  return { changed, agreement: Math.round((agreed / SCENARIOS.length) * 100) };
}

describe("sensitivity of [X] design parameters (report only)", () => {
  it("prints and saves how many scenario actions change at ±10%", () => {
    const baseline = SCENARIOS.map((s) => runScenario(s).action);
    const base = evaluate(DEFAULT_FUZZY_PARAMS, baseline);
    const n = SCENARIOS.length;

    const rows = PARAMETERS.map(([name, perturb]) => {
      const down = evaluate(perturb(DEFAULT_FUZZY_PARAMS, 1 - STEP), baseline);
      const up = evaluate(perturb(DEFAULT_FUZZY_PARAMS, 1 + STEP), baseline);
      return { name, down, up };
    });

    const lines = [
      "# Sensitivity report: [X] design parameters ±10%",
      "",
      `Generated by \`tests/sensitivity.test.ts\`. ${n} scenarios; baseline agreement ${base.agreement}%.`,
      "Changed = scenarios whose action differs from the baseline run. Breakpoints at domain edges (0, 1, 8, 100) are not moved.",
      "",
      "| Parameter [X] | −10%: changed | −10%: agreement | +10%: changed | +10%: agreement |",
      "|---|---|---|---|---|",
      ...rows.map(
        (r) => `| ${r.name} | ${r.down.changed}/${n} | ${r.down.agreement}% | ${r.up.changed}/${n} | ${r.up.agreement}% |`,
      ),
      "",
    ];
    const report = lines.join("\n");
    writeFileSync(fileURLToPath(new URL("./sensitivity_report.md", import.meta.url)), report, "utf8");
    console.log(report);
  });
});
